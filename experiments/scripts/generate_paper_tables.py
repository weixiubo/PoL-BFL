"""
Generate LaTeX Tables for Paper

This script generates publication-ready LaTeX tables from experiment results.
Includes:
- Statistical significance markers (*, **, ***)
- Bold formatting for best results
- Proper formatting with mean±std
- Automatic comparison against baselines

Usage:
    python generate_paper_tables.py --experiment rq1 --input results/rq1_aggregated.json
    python generate_paper_tables.py --experiment rq2 --input results/rq2_aggregated.json
"""

import argparse
import json
import numpy as np
from pathlib import Path
import logging
import sys

# Add utils to path
scripts_dir = Path(__file__).parent
sys.path.insert(0, str(scripts_dir / 'utils'))

from statistical_analysis import format_with_significance

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)


def generate_rq1_table(aggregated_results, output_path):
    """
    Generate RQ1 security evaluation table
    
    Format:
    Attack | Method | MA | TPR_cond | TPR_e2e | FPR
    """
    logger.info("Generating RQ1 table...")
    
    with open(output_path, 'w') as f:
        # Header
        f.write("% RQ1: Security Evaluation Results\n")
        f.write("% Generated by generate_paper_tables.py\n")
        f.write("% Significance markers: * p<0.05, ** p<0.01, *** p<0.001\n\n")
        
        f.write("\\begin{table*}[t]\n")
        f.write("\\centering\n")
        f.write("\\caption{RQ1: Security Evaluation Against Byzantine and Free-riding Attacks}\n")
        f.write("\\label{tab:rq1_security}\n")
        f.write("\\resizebox{\\textwidth}{!}{%\n")
        f.write("\\begin{tabular}{l|l|cccc}\n")
        f.write("\\toprule\n")
        f.write("\\textbf{Attack Type} & \\textbf{Method} & \\textbf{MA (\\%)} & \\textbf{TPR$_{cond}$ (\\%)} & \\textbf{TPR$_{e2e}$ (\\%)} & \\textbf{FPR (\\%)} \\\\\n")
        f.write("\\midrule\n")
        
        # Sort attacks
        attack_order = [
            'no_attack',
            'byzantine_random_noise',
            'byzantine_label_flipping',
            'byzantine_model_replacement',
            'byzantine_gradient_inversion',
            'free_riding_no_training',
            'free_riding_lazy_training',
            'sybil_attack'
        ]
        
        # Method order
        method_order = ['Vanilla_FL', 'Krum', 'Trimmed_Mean', 'Median', 'PoL_FL']
        
        for attack in attack_order:
            if attack not in aggregated_results:
                continue
            
            baselines = aggregated_results[attack]
            
            # Find best accuracy (excluding PoL_FL for comparison)
            best_acc = 0.0
            for method in method_order:
                if method != 'PoL_FL' and method in baselines:
                    acc = baselines[method]['final_accuracy']['mean']
                    if acc > best_acc:
                        best_acc = acc
            
            # Write rows for this attack
            num_methods = len([m for m in method_order if m in baselines])
            
            for i, method in enumerate(method_order):
                if method not in baselines:
                    continue
                
                metrics = baselines[method]
                
                # Extract metrics
                ma = metrics['final_accuracy']
                tpr_cond = metrics['tpr_conditional']
                tpr_e2e = metrics['tpr_e2e']
                fpr = metrics['fpr']
                
                # Get p-value if available
                p_val = metrics.get('significance_vs_best', {}).get('p_value')
                
                # Format values
                ma_str = format_with_significance(ma['mean'] * 100, ma['std'] * 100, p_val, decimals=1)
                tpr_cond_str = format_with_significance(tpr_cond['mean'] * 100, tpr_cond['std'] * 100, decimals=1)
                tpr_e2e_str = format_with_significance(tpr_e2e['mean'] * 100, tpr_e2e['std'] * 100, decimals=1)
                fpr_str = format_with_significance(fpr['mean'] * 100, fpr['std'] * 100, decimals=1)
                
                # Bold best values
                if method == 'PoL_FL' or ma['mean'] >= best_acc:
                    ma_str = f"\\textbf{{{ma_str}}}"
                
                # Attack name (only for first method)
                if i == 0:
                    attack_name = attack.replace('_', ' ').title()
                    f.write(f"\\multirow{{{num_methods}}}{{*}}{{{attack_name}}} & {method} & {ma_str} & {tpr_cond_str} & {tpr_e2e_str} & {fpr_str} \\\\\n")
                else:
                    f.write(f" & {method} & {ma_str} & {tpr_cond_str} & {tpr_e2e_str} & {fpr_str} \\\\\n")
            
            f.write("\\midrule\n")
        
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
        f.write("}%\n")
        f.write("\\end{table*}\n")
    
    logger.info(f"Saved RQ1 table to {output_path}")


def generate_rq2_table(aggregated_results, output_path):
    """
    Generate RQ2 ablation study table
    
    Format:
    Variant | MA | DR | Overhead
    """
    logger.info("Generating RQ2 table...")
    
    with open(output_path, 'w') as f:
        # Header
        f.write("% RQ2: Ablation Study Results\n")
        f.write("% Generated by generate_paper_tables.py\n\n")
        
        f.write("\\begin{table}[t]\n")
        f.write("\\centering\n")
        f.write("\\caption{RQ2: Ablation Study - Component Contributions}\n")
        f.write("\\label{tab:rq2_ablation}\n")
        f.write("\\begin{tabular}{l|ccc}\n")
        f.write("\\toprule\n")
        f.write("\\textbf{Variant} & \\textbf{MA (\\%)} & \\textbf{DR (\\%)} & \\textbf{Overhead} \\\\\n")
        f.write("\\midrule\n")
        
        # Variant order
        variant_order = [
            'vanilla_fl',
            'pol_only',
            'pol_zkp',
            'pol_incentive',
            'pol_zkp_incentive'
        ]
        
        variant_names = {
            'vanilla_fl': 'Vanilla FL',
            'pol_only': 'PoL Only',
            'pol_zkp': 'PoL + ZKP',
            'pol_incentive': 'PoL + Incentive',
            'pol_zkp_incentive': 'Full System'
        }
        
        for variant in variant_order:
            if variant not in aggregated_results:
                continue
            
            metrics = aggregated_results[variant]
            
            # Extract metrics
            ma = metrics['final_accuracy']
            dr = metrics.get('detection_rate', {'mean': 0.0, 'std': 0.0})
            overhead = metrics.get('overhead', {'mean': 1.0, 'std': 0.0})
            
            # Format values
            ma_str = format_with_significance(ma['mean'] * 100, ma['std'] * 100, decimals=1)
            dr_str = format_with_significance(dr['mean'] * 100, dr['std'] * 100, decimals=1)
            overhead_str = f"{overhead['mean']:.2f}×"
            
            # Bold full system
            if variant == 'pol_zkp_incentive':
                ma_str = f"\\textbf{{{ma_str}}}"
            
            f.write(f"{variant_names[variant]} & {ma_str} & {dr_str} & {overhead_str} \\\\\n")
        
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
        f.write("\\end{table}\n")
    
    logger.info(f"Saved RQ2 table to {output_path}")


def generate_rq3_table(aggregated_results, output_path):
    """
    Generate RQ3 overhead analysis table
    
    Format:
    Method | Training Time | Communication | Storage | ZKP | Gas Cost
    """
    logger.info("Generating RQ3 table...")
    
    with open(output_path, 'w') as f:
        # Header
        f.write("% RQ3: System Overhead Analysis\n")
        f.write("% Generated by generate_paper_tables.py\n\n")
        
        f.write("\\begin{table}[t]\n")
        f.write("\\centering\n")
        f.write("\\caption{RQ3: System Overhead Comparison}\n")
        f.write("\\label{tab:rq3_overhead}\n")
        f.write("\\begin{tabular}{l|ccccc}\n")
        f.write("\\toprule\n")
        f.write("\\textbf{Method} & \\textbf{Training} & \\textbf{Comm.} & \\textbf{Storage} & \\textbf{ZKP} & \\textbf{Gas} \\\\\n")
        f.write(" & \\textbf{Time (s)} & \\textbf{(MB)} & \\textbf{(MB)} & \\textbf{(s)} & \\textbf{(ETH)} \\\\\n")
        f.write("\\midrule\n")
        
        method_order = ['Vanilla_FL', 'PoL_FL', 'PoL_FL_ZKP']
        
        for method in method_order:
            if method not in aggregated_results:
                continue
            
            metrics = aggregated_results[method]
            
            # Extract metrics
            train_time = metrics.get('training_time', {'mean': 0.0, 'std': 0.0})
            comm = metrics.get('communication_cost', {'mean': 0.0, 'std': 0.0})
            storage = metrics.get('storage_cost', {'mean': 0.0, 'std': 0.0})
            zkp_time = metrics.get('zkp_time', {'mean': 0.0, 'std': 0.0})
            gas_cost = metrics.get('gas_cost', {'mean': 0.0, 'std': 0.0})
            
            # Format values
            train_str = format_with_significance(train_time['mean'], train_time['std'], decimals=1)
            comm_str = format_with_significance(comm['mean'], comm['std'], decimals=1)
            storage_str = format_with_significance(storage['mean'], storage['std'], decimals=1)
            zkp_str = format_with_significance(zkp_time['mean'], zkp_time['std'], decimals=2) if zkp_time['mean'] > 0 else '-'
            gas_str = f"{gas_cost['mean']:.4f}" if gas_cost['mean'] > 0 else '-'
            
            f.write(f"{method} & {train_str} & {comm_str} & {storage_str} & {zkp_str} & {gas_str} \\\\\n")
        
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
        f.write("\\end{table}\n")
    
    logger.info(f"Saved RQ3 table to {output_path}")


def generate_rq4_table(aggregated_results, output_path):
    """
    Generate RQ4 incentive mechanism table
    
    Format:
    Scenario | Participation | Attack Success | Honest Utility | Rational Utility
    """
    logger.info("Generating RQ4 table...")
    
    with open(output_path, 'w') as f:
        # Header
        f.write("% RQ4: Incentive Mechanism Effectiveness\n")
