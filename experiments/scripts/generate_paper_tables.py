def main():
    parser = argparse.ArgumentParser(description='Generate LaTeX tables for paper')
    parser.add_argument('--experiment', type=str, required=True,
                       choices=['rq1', 'rq2', 'rq3', 'rq4', 'rq5', 'all'],
                       help='Experiment type')
    parser.add_argument('--input', type=str, required=True,
                       help='Input JSON file with aggregated results')
    parser.add_argument('--output_dir', type=str, default=None,
                       help='Output directory (default: same as input)')
    
    args = parser.parse_args()
    
    # Load results
    with open(args.input, 'r') as f:
        results = json.load(f)
    
    # Set output directory
    if args.output_dir:
        output_dir = Path(args.output_dir)
    else:
        output_dir = Path(args.input).parent
    
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Generate tables
    if args.experiment == 'rq1' or args.experiment == 'all':
        output_path = output_dir / 'rq1_table.tex'
        generate_rq1_table(results, output_path)
    
    if args.experiment == 'rq2' or args.experiment == 'all':
        output_path = output_dir / 'rq2_table.tex'
        generate_rq2_table(results, output_path)
    
    if args.experiment == 'rq3' or args.experiment == 'all':
        output_path = output_dir / 'rq3_table.tex'
        generate_rq3_table(results, output_path)
    
    if args.experiment == 'rq4' or args.experiment == 'all':
        output_path = output_dir / 'rq4_table.tex'
        generate_rq4_table(results, output_path)
    
    if args.experiment == 'rq5' or args.experiment == 'all':
        output_path = output_dir / 'rq5_table.tex'
        generate_rq5_table(results, output_path)
    
    logger.info(f"\nAll tables saved to {output_dir}")


if __name__ == '__main__':
    main()

